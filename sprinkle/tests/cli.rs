const BIN: &str = env!("CARGO_BIN_EXE_sprinkle");
#[test]
fn cli_basics() {
    basics(BIN, "sprinkle");
    let f = Fixture::new(BIN, false);
    for locale in ["C", "zh_CN.UTF-8"] {
        let output = f
            .cmd()
            .arg("--help")
            .env("LC_ALL", locale)
            .output()
            .unwrap();
        code(&output, 0);
        assert!(!text(&output.stdout).contains("SPRINKLE_SEED"));
    }
}
fn fixture() -> Fixture {
    let mut f = Fixture::new(BIN, true);
    f.env.push(("SPRINKLE_SEED", "42"));
    for i in 0..40 {
        fs::write(f.repo.join(format!("f{i}.rs")), "fn main() {}\n").unwrap();
    }
    fs::write(f.repo.join(".gitignore"), "target/\n").unwrap();
    f.git(&["add", "."]);
    f.git(&["commit", "-qm", "files"]);
    f
}
#[test]
fn isolated_reproducible_patch_and_undo() {
    let f = fixture();
    let head = f.git(&["rev-parse", "HEAD"]).stdout;
    let branch = f.git(&["symbolic-ref", "HEAD"]).stdout;
    code(&f.run(&[]), 0);
    let copy = f.copy();
    assert!(f.git(&["status", "--porcelain"]).stdout.is_empty());
    assert_eq!(f.git(&["rev-parse", "HEAD"]).stdout, head);
    assert_eq!(f.git(&["symbolic-ref", "HEAD"]).stdout, branch);
    assert_eq!(
        fs::metadata(&copy).unwrap().permissions().mode() & 0o777,
        0o700
    );
    let diff = f.run(&["diff"]);
    code(&diff, 0);
    assert!(text(&diff.stdout).contains("+//"));
    code(&f.cmd().current_dir(&copy).arg("undo").output().unwrap(), 1);
    code(&f.run(&["undo"]), 0);
    assert!(!copy.exists());
    code(&f.run(&["undo"]), 1);
    code(&f.run(&["worktree"]), 0);
    assert_eq!(f.run(&["diff"]).stdout, diff.stdout);
    code(&f.run(&["undo"]), 0);
}
