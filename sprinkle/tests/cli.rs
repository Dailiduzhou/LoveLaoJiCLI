#[test]
fn protects_edits_ignored_staged_commits_and_locks() {
    let f = fixture();
    code(&f.run(&[]), 0);
    let copy = f.copy();
    let original = fs::read(copy.join("code.rs")).unwrap();
    fs::write(copy.join("code.rs"), "user work\n").unwrap();
    code(&f.run(&["undo"]), 1);
    assert!(copy.exists());
    let diff = f.run(&["diff"]);
    code(&diff, 0);
    assert!(!text(&diff.stdout).contains("user work"));
    assert!(text(&diff.stderr).contains("creation-time"));
    fs::write(copy.join("code.rs"), original).unwrap();
    fs::create_dir(copy.join("target")).unwrap();
    fs::write(copy.join("target/build"), "x").unwrap();
    code(&f.run(&["undo"]), 1);
    fs::remove_dir_all(copy.join("target")).unwrap();
    f.git(&["worktree", "lock", copy.to_str().unwrap()]);
    code(&f.run(&["undo"]), 1);
    f.git(&["worktree", "unlock", copy.to_str().unwrap()]);
    let mut c = std::process::Command::new("git");
    f.environment(&mut c);
    assert!(c
        .current_dir(&copy)
        .args(["add", "."])
        .status()
        .unwrap()
        .success());
    code(&f.run(&["undo"]), 1);
    let mut c = std::process::Command::new("git");
    f.environment(&mut c);
    assert!(c
        .current_dir(&copy)
        .args(["commit", "-qm", "keep it"])
        .status()
        .unwrap()
        .success());
    code(&f.run(&["undo"]), 1);
}
#[test]
fn skips_unsafe_files_and_preserves_modes() {
    let f = fixture();
    fs::write(f.repo.join("raw.rs"), "let s=r###\"open\"##;\n").unwrap();
    fs::write(
        f.repo.join("generated.go"),
        "// Code generated by test. DO NOT EDIT\npackage p\n",
    )
    .unwrap();
    fs::write(f.repo.join("unclosed.md"), "```\nhello\n").unwrap();
    symlink("/etc/passwd", f.repo.join("link.rs")).unwrap();
    // Make all ordinary candidates executable so at least one edited file,
    // not merely an untouched random candidate, exercises mode preservation.
    for i in 0..40 {
        fs::set_permissions(
            f.repo.join(format!("f{i}.rs")),
            fs::Permissions::from_mode(0o755),
        )
        .unwrap();
    }
    f.git(&["add", "."]);
    f.git(&["commit", "-qm", "edge cases"]);
    code(&f.run(&[]), 0);
    let copy = f.copy();
    for p in ["raw.rs", "generated.go", "unclosed.md"] {
        assert_eq!(
            fs::read(copy.join(p)).unwrap(),
            fs::read(f.repo.join(p)).unwrap()
        );
    }
    assert_eq!(
        fs::read_link(copy.join("link.rs")).unwrap(),
        std::path::PathBuf::from("/etc/passwd")
    );
    let manifest: serde_json::Value = f
        .store()
        .read(&f.find("manifest.json").pop().unwrap())
        .unwrap()
        .unwrap();
    // Unchanged unsafe files alone prove nothing: random selection may skip
    // them even if the syntax/symlink guards have been removed.
    assert_eq!(manifest["skipped"]["syntax-or-text"], 3);
    assert_eq!(manifest["skipped"]["symlink"], 1);
    let mut edited_executables = 0;
    for file in manifest["files"].as_array().unwrap() {
        let bytes: Vec<u8> = serde_json::from_value(file["path"].clone()).unwrap();
        let path = cli_common::state::path_from(&bytes);
        if file["mode"].as_u64().unwrap() & 0o777 == 0o755
            && !file["addition"].as_str().unwrap().is_empty()
        {
            edited_executables += 1;
            assert_ne!(
                fs::read(copy.join(&path)).unwrap(),
                fs::read(f.repo.join(&path)).unwrap()
            );
            assert_eq!(
                fs::metadata(copy.join(path)).unwrap().permissions().mode() & 0o777,
                0o755
            );
        }
    }
    assert!(edited_executables > 0);
    code(&f.run(&["undo"]), 0);
}
#[test]
fn disables_hooks_and_refuses_filters() {
    let f = fixture();
    let marker = f.root.join("hook-ran");
    let hook = f.repo.join(".git/hooks/post-checkout");
    fs::write(&hook, format!("#!/bin/sh\ntouch '{}'\n", marker.display())).unwrap();
    fs::set_permissions(hook, fs::Permissions::from_mode(0o755)).unwrap();
    code(&f.run(&[]), 0);
    assert!(!marker.exists());
    code(&f.run(&["undo"]), 0);
    f.git(&[
        "config",
        "filter.bad.smudge",
        &format!("touch '{}'", marker.display()),
    ]);
    code(&f.run(&[]), 1);
    assert!(!marker.exists());
}
